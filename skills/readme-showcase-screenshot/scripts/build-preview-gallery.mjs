#!/usr/bin/env node
import fs from "node:fs/promises";
import path from "node:path";
import { ensureDir, loadConfig, parseArgs, readManifest, relPath, writeManifest } from "./common.mjs";

const args = parseArgs();
const config = await loadConfig(args.config || "showcase.config.json");
const manifest = await readManifest(config.outputDir);
await ensureDir(config.outputDir);

const galleryPath = path.join(config.outputDir, config.gallery?.file || "gallery.html");
await fs.writeFile(galleryPath, buildGallery(config, manifest), "utf8");
manifest.gallery = { path: relPath(config.outputDir, galleryPath) };
await writeManifest(config.outputDir, manifest);
console.log(`Built gallery -> ${galleryPath}`);

function buildGallery(config, manifest) {
  const hero = manifest.hero
    ? `<section class="hero-preview"><img src="${manifest.hero.path}" alt="${escapeHtml(manifest.hero.title)}"></section>`
    : "";
  const staticCards = (manifest.static || [])
    .map(
      (item) => `<article class="card">
  <img src="${item.path}" alt="${escapeHtml(item.title)}" loading="lazy">
  <div><strong>${escapeHtml(item.title)}</strong><span>${escapeHtml(item.viewport)} · ${item.width}x${item.height}</span></div>
</article>`
    )
    .join("\n");
  const motionCards = (manifest.motion || [])
    .map((item) => {
      const source = item.mp4 || item.webm;
      const gif = item.gif ? `<a href="${item.gif}">GIF</a>` : "";
      return `<article class="card video-card">
  <video src="${source}" controls muted loop playsinline></video>
  <div><strong>${escapeHtml(item.title)}</strong><span>${escapeHtml(item.viewport)} · <a href="${item.webm}">WebM</a> ${item.mp4 ? `· <a href="${item.mp4}">MP4</a>` : ""} ${gif}</span></div>
</article>`;
    })
    .join("\n");

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width,initial-scale=1" />
<title>${escapeHtml(config.projectName || "Project")} Preview Gallery</title>
<style>
:root{color-scheme:dark;--bg:#101827;--panel:#172033;--text:#eef2ff;--muted:#a5b4fc;--line:#334155;--accent:#38bdf8}*{box-sizing:border-box}body{margin:0;background:linear-gradient(135deg,#0f172a,#111827 55%,#172554);color:var(--text);font-family:Inter,ui-sans-serif,system-ui,-apple-system,BlinkMacSystemFont,"Segoe UI",sans-serif}header{padding:56px min(6vw,80px) 24px}h1{font-size:clamp(38px,6vw,76px);line-height:1;margin:0;letter-spacing:0}p{font-size:18px;color:#cbd5e1;max-width:760px;line-height:1.6}.hero-preview{padding:0 min(6vw,80px) 28px}.hero-preview img{width:100%;max-width:1180px;border-radius:18px;border:1px solid #ffffff33;box-shadow:0 28px 90px #0008}.section{padding:22px min(6vw,80px) 56px}h2{font-size:28px;margin:0 0 18px}.grid{display:grid;grid-template-columns:repeat(auto-fit,minmax(280px,1fr));gap:22px}.card{background:#ffffff10;border:1px solid #ffffff24;border-radius:14px;overflow:hidden;box-shadow:0 20px 60px #0005}.card img,.card video{display:block;width:100%;aspect-ratio:16/10;object-fit:cover;background:#020617}.video-card video{aspect-ratio:16/9}.card div{display:flex;justify-content:space-between;gap:12px;padding:14px 16px;align-items:center}.card span{font-size:13px;color:#c4b5fd}.card a{color:#7dd3fc}footer{padding:20px min(6vw,80px) 48px;color:#94a3b8}
</style>
</head>
<body>
<header>
  <h1>${escapeHtml(config.projectName || "Project")} Preview Gallery</h1>
  <p>Generated from local project states for README, docs, releases, and visual QA. Keep README focused; use this page as the full visual archive.</p>
</header>
${hero}
<section class="section">
  <h2>Static Screenshots</h2>
  <div class="grid">${staticCards || "<p>No static screenshots captured yet.</p>"}</div>
</section>
<section class="section">
  <h2>Motion Demos</h2>
  <div class="grid">${motionCards || "<p>No motion demos captured yet.</p>"}</div>
</section>
<footer>Generated by readme-showcase-screenshot.</footer>
</body>
</html>`;
}

function escapeHtml(value) {
  return String(value || "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}
